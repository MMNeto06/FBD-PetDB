CREATE PROCEDURE SP_DeleteClinic 
		@ClinicNIF int
AS 
BEGIN 
	SET NOCOUNT ON; 

	BEGIN TRY
		BEGIN TRANSACTION SCHEDULEDELETE 
			DELETE FROM PETDB_ClinicaVeterinaria
			WHERE NIF=@ClinicNIF;
		COMMIT TRANSACTION SCHEDULEDELETE
	END TRY
	BEGIN CATCH
		ROLLBACK TRANSACTION SCHEDULEDELETE
	END CATCH
END
GO

